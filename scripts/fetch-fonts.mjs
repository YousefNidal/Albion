import fs from "node:fs";
import path from "node:path";

const OUT_DIR = path.resolve("public/fonts");
const CSS_OUT = path.resolve("app/fonts.css");
fs.mkdirSync(OUT_DIR, { recursive: true });

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/125.0 Safari/537.36";

const FAMILIES = [
  { file: "old-standard-tt", css: "Old+Standard+TT:wght@400;700", keep: ["latin", "latin-ext", "cyrillic"] },
  { file: "pt-sans", css: "PT+Sans:wght@400;700", keep: ["latin", "latin-ext", "cyrillic", "cyrillic-ext"] },
  { file: "jetbrains-mono", css: "JetBrains+Mono:wght@400;600", keep: ["latin", "latin-ext", "cyrillic"] },
];

const blocks = [];

for (const fam of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${fam.css}&display=swap`;
  const r = await fetch(url, { headers: { "User-Agent": UA } });
  if (!r.ok) throw new Error(`CSS ${r.status} for ${url}`);
  const css = await r.text();
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g;
  let n = 0;
  for (const m of css.matchAll(re)) {
    const subset = m[1];
    if (!fam.keep.includes(subset)) continue;
    let block = m[2];
    const urlMatch = block.match(/url\((https:[^)]+\.woff2)\)/);
    if (!urlMatch) continue;
    const fontUrl = urlMatch[1];
    const weight = (block.match(/font-weight:\s*(\d+)/) || [])[1] || "400";
    const style = (block.match(/font-style:\s*(\w+)/) || [])[1] || "normal";
    const fname = `${fam.file}-${weight}-${style}-${subset}.woff2`;
    const fpath = path.join(OUT_DIR, fname);
    if (!fs.existsSync(fpath)) {
      const fr = await fetch(fontUrl, { headers: { "User-Agent": UA } });
      if (!fr.ok) throw new Error(`font ${fr.status} ${fontUrl}`);
      fs.writeFileSync(fpath, Buffer.from(await fr.arrayBuffer()));
    }
    block = block.replace(/url\(https:[^)]+\.woff2\)/, `url(/fonts/${fname})`);
    blocks.push(block.replace(/\s+/g, " ").trim());
    n++;
  }
  console.log(`${fam.file}: ${n} faces`);
}

fs.writeFileSync(
  CSS_OUT,
  "/* generated by scripts/fetch-fonts.mjs — Google Fonts (OFL) */\n" + blocks.join("\n") + "\n",
  "utf8"
);
console.log(`wrote ${CSS_OUT} (${blocks.length} faces)`);
